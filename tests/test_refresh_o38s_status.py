"""Tests of tools/refresh_o38s_status.py against a throwaway repository with a stand-in generator.

Run: python -m unittest discover -s tests -p "test_*.py"
"""

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import refresh_o38s_status as refresh  # noqa: E402

# Stand-in for jomission's scripts/open38_status.py: writes the JSON in generator.json, with source.sha set to
# HEAD unless the fixture pins it, and exits with the code in generator.rc when that file exists.
GENERATOR = '''import json, subprocess, sys
from pathlib import Path
out, repo = sys.argv[1], Path(sys.argv[sys.argv.index("--repo") + 1])
rc = repo / "generator.rc"
if rc.exists():
    sys.exit(int(rc.read_text()))
raw = (repo / "generator.json").read_text(encoding="utf-8")
if raw.startswith("{"):
    status = json.loads(raw)
    head = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    status.setdefault("source", {}).setdefault("sha", head)
    raw = json.dumps(status)
Path(out).write_text(raw, encoding="utf-8")
'''

GOOD = {
    "schema": "o38s_status/1",
    "generated_utc": "2026-11-17T18:30:34Z",
    "source": {"branch": "main", "dirty_tracked": False, "repo_url": "https://github.com/HNXJ/jomission"},
    "stage1": {"status": "PASS", "public_status": "PASS"},
}


def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@example.invalid", *args],
                   check=True, capture_output=True, stdin=subprocess.DEVNULL)


class RefreshTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        base = Path(self.tmp.name)
        self.origin = base / "origin.git"
        self.repo = base / "jomission"
        self.out = base / "site" / "assets" / "data" / "o38s_status.js"
        subprocess.run(["git", "init", "-q", "--bare", "-b", "main", str(self.origin)], check=True)
        subprocess.run(["git", "init", "-q", "-b", "main", str(self.repo)], check=True)
        (self.repo / "scripts").mkdir()
        (self.repo / "scripts" / "open38_status.py").write_text(GENERATOR, encoding="utf-8")
        self.commit(GOOD)
        git(self.repo, "remote", "add", "origin", str(self.origin))
        git(self.repo, "push", "-q", "origin", "main")

    def commit(self, status=None, raw=None):
        text = raw if raw is not None else json.dumps(status)
        (self.repo / "generator.json").write_text(text, encoding="utf-8")
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-q", "-m", "fixture")

    def run_tool(self, *extra):
        return refresh.main(["--jomission", str(self.repo), "--out", str(self.out), *extra])

    def stored(self):
        text = self.out.read_text(encoding="utf-8")
        body = text[text.index("window.O38S_STATUS = ") + len("window.O38S_STATUS = "):].rstrip().rstrip(";")
        return json.loads(body)

    def assert_refused(self, *extra):
        self.out.parent.mkdir(parents=True, exist_ok=True)
        self.out.write_text("previous snapshot", encoding="utf-8")
        self.assertEqual(self.run_tool(*extra), 1)
        self.assertEqual(self.out.read_text(encoding="utf-8"), "previous snapshot", "a refusal must not write")

    def head(self):
        return subprocess.run(["git", "-C", str(self.repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()

    def test_clean_checkout_at_the_remote_tip_is_stored_unchanged(self):
        self.assertEqual(self.run_tool(), 0)
        stored = self.stored()
        expected = json.loads(json.dumps(GOOD))
        expected["source"]["sha"] = self.head()
        self.assertEqual(stored, expected)
        self.assertEqual(stored["stage1"]["public_status"], "PASS")
        self.assertTrue(self.out.read_text(encoding="utf-8").startswith("// Generated by tools/refresh_o38s_status.py"))
        self.assertNotIn(b"\r\n", self.out.read_bytes())

    def test_modified_tracked_file_is_refused(self):
        (self.repo / "generator.json").write_text(json.dumps(dict(GOOD, stage1={"status": "FAIL"})), encoding="utf-8")
        self.assert_refused()

    def test_generator_failure_is_refused(self):
        (self.repo / "generator.rc").write_text("3", encoding="utf-8")  # untracked, so the tree still counts as clean
        self.assert_refused()

    def test_output_that_is_not_json_is_refused(self):
        self.commit(raw="not json")
        git(self.repo, "push", "-q", "origin", "main")
        self.assert_refused()

    def test_other_schema_is_refused(self):
        self.commit(dict(GOOD, schema="o38s_status/2"))
        git(self.repo, "push", "-q", "origin", "main")
        self.assert_refused()

    def test_source_sha_that_is_not_head_is_refused(self):
        self.commit(dict(GOOD, source=dict(GOOD["source"], sha="0" * 40)))
        git(self.repo, "push", "-q", "origin", "main")
        self.assert_refused()

    def test_dirty_source_flag_is_refused(self):
        for flag in (True, None, "false"):
            self.commit(dict(GOOD, source=dict(GOOD["source"], dirty_tracked=flag)))
            git(self.repo, "push", "-q", "origin", "main")
            self.assert_refused()

    def test_missing_generation_time_is_refused(self):
        status = dict(GOOD)
        del status["generated_utc"]
        self.commit(status)
        git(self.repo, "push", "-q", "origin", "main")
        self.assert_refused()

    def test_checkout_that_is_not_the_remote_tip_is_refused(self):
        self.commit(dict(GOOD, generated_utc="2026-11-17T19:00:00Z"))  # local commit, not pushed: origin is behind
        self.assert_refused()
        self.assertEqual(self.run_tool("--no-remote-check"), 0)  # the same checkout without the comparison
        self.assertEqual(self.stored()["generated_utc"], "2026-11-17T19:00:00Z")


if __name__ == "__main__":
    unittest.main()
