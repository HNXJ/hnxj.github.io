#!/usr/bin/env python3
"""Refresh the Jomission/LANSA (OPEN-38) status snapshot the Labyrinth cards read.

Runs jomission's own generator (`scripts/open38_status.py`, schema o38s_status/1) in a clean jomission checkout
and stores its JSON, unchanged, as `assets/data/o38s_status.js` (`window.O38S_STATUS = {...};`). This tool holds
no status logic: it only refuses a snapshot whose provenance cannot be trusted. On a refusal nothing is written,
so the cards keep the previous snapshot until it ages into UNKNOWN (assets/o38s_view.js, MAX_AGE_HOURS).

Refused: a checkout with modified tracked files; a generator that fails; a JSON of another schema; a
`source.sha` that is not the checkout's HEAD; `source.dirty_tracked` not false; a checkout that is not at the
tip of its branch on `origin` (skipped with --no-remote-check, for a checkout without a remote).

Usage:
  python tools/refresh_o38s_status.py --jomission <checkout> [--out assets/data/o38s_status.js]
                                      [--run-tests] [--no-remote-check]
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

SCHEMA = "o38s_status/1"
ROOT = Path(__file__).resolve().parents[1]
HEADER = (
    "// Generated by tools/refresh_o38s_status.py from jomission scripts/open38_status.py. Do not edit:\n"
    "// rerun the tool. The cards show these statuses through assets/o38s_view.js.\n"
)


class Refused(Exception):
    pass


def git(repo, *args):
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if r.returncode != 0:
        raise Refused(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout.strip()


def snapshot(repo, run_tests=False, remote_check=True):
    """The generator's JSON for the checkout, or Refused."""
    repo = Path(repo)
    head = git(repo, "rev-parse", "HEAD")
    if git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise Refused("the jomission checkout has modified tracked files")
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "status.json"
        cmd = [sys.executable, "-B", str(repo / "scripts" / "open38_status.py"), str(out), "--repo", str(repo)]
        if run_tests:
            cmd.append("--run-tests")
        r = subprocess.run(cmd, capture_output=True, text=True, stdin=subprocess.DEVNULL)
        if r.returncode != 0 or not out.exists():
            raise Refused(f"the generator failed (exit {r.returncode}): {r.stderr.strip()[-300:]}")
        try:
            status = json.loads(out.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise Refused(f"the generator's output is not JSON: {exc}")
    if not isinstance(status, dict) or status.get("schema") != SCHEMA:
        raise Refused(f"schema is not {SCHEMA}")
    source = status.get("source") if isinstance(status.get("source"), dict) else {}
    if source.get("sha") != head:
        raise Refused(f"source.sha {source.get('sha')} is not the checkout's HEAD {head}")
    if source.get("dirty_tracked") is not False:
        raise Refused("source.dirty_tracked is not false")
    if not isinstance(status.get("generated_utc"), str) or not status["generated_utc"]:
        raise Refused("no generated_utc")
    if remote_check:
        branch = source.get("branch")
        if not isinstance(branch, str) or not branch:
            raise Refused("no source.branch to compare with origin")
        remote = git(repo, "ls-remote", "origin", f"refs/heads/{branch}").split()
        if len(remote) != 2 or remote[0] != head:
            raise Refused(f"the checkout ({head[:10]}) is not the tip of origin/{branch} ({remote[0][:10] if remote else 'absent'})")
    return status


def write_snapshot(status, out):
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    body = HEADER + "window.O38S_STATUS = " + json.dumps(status, indent=1, ensure_ascii=True) + ";\n"
    out.write_bytes(body.encode("utf-8"))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Refresh the OPEN-38 status snapshot for the Labyrinth cards.")
    ap.add_argument("--jomission", required=True, help="a clean jomission checkout")
    ap.add_argument("--out", default=str(ROOT / "assets" / "data" / "o38s_status.js"))
    ap.add_argument("--run-tests", action="store_true", help="pass --run-tests to the generator")
    ap.add_argument("--no-remote-check", action="store_true", help="do not compare the checkout with origin")
    args = ap.parse_args(argv)
    try:
        status = snapshot(args.jomission, args.run_tests, not args.no_remote_check)
    except Refused as exc:
        sys.stderr.write(f"REFUSED, snapshot not written: {exc}\n")
        return 1
    write_snapshot(status, args.out)
    print(f"wrote {args.out}: source {status['source']['sha'][:10]}, generated {status['generated_utc']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
